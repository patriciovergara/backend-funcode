CREATE TABLE IF NOT EXISTS projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  description TEXT NOT NULL,
  project_url TEXT NOT NULL UNIQUE,
  image_url TEXT,
  technologies TEXT[] NOT NULL DEFAULT '{}',
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  is_published BOOLEAN NOT NULL DEFAULT TRUE,
  display_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT projects_title_not_blank CHECK (LENGTH(TRIM(title)) > 0),
  CONSTRAINT projects_description_not_blank CHECK (LENGTH(TRIM(description)) > 0),
  CONSTRAINT projects_project_url_not_blank CHECK (LENGTH(TRIM(project_url)) > 0),
  CONSTRAINT projects_display_order_nonnegative CHECK (display_order >= 0)
);

CREATE INDEX IF NOT EXISTS projects_public_order_idx
  ON projects (is_published, featured DESC, display_order, created_at DESC);

